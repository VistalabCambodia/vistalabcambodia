-- Run once in Supabase SQL Editor to enable the admin traffic dashboard.
-- Stores page and product views with a random, session-only identifier. No IP,
-- email, name, or other personal details are stored by this feature.

create table if not exists public.website_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('page_view', 'product_view')),
  page_path text not null check (char_length(page_path) between 1 and 80),
  product_id text check (product_id is null or char_length(product_id) <= 120),
  product_name text check (product_name is null or char_length(product_name) <= 160),
  visitor_id text not null check (char_length(visitor_id) between 1 and 80),
  created_at timestamptz not null default now(),
  constraint product_view_has_product check (event_type <> 'product_view' or product_id is not null)
);

create index if not exists website_events_created_at_idx
  on public.website_events (created_at desc);
create index if not exists website_events_product_idx
  on public.website_events (product_id, created_at desc)
  where event_type = 'product_view';

alter table public.website_events enable row level security;

drop policy if exists "Visitors can record website events" on public.website_events;
create policy "Visitors can record website events"
  on public.website_events for insert to anon, authenticated
  with check (
    event_type in ('page_view', 'product_view')
    and char_length(page_path) between 1 and 80
    and char_length(visitor_id) between 1 and 80
    and (product_id is null or char_length(product_id) <= 120)
    and (product_name is null or char_length(product_name) <= 160)
  );

drop policy if exists "Admins can read website events" on public.website_events;
create policy "Admins can read website events"
  on public.website_events for select to authenticated
  using (
    exists (
      select 1 from public.admin_users
      where admin_users.user_id = auth.uid()
    )
  );

revoke all on public.website_events from anon, authenticated;
grant insert on public.website_events to anon, authenticated;
grant select on public.website_events to authenticated;
grant usage on sequence public.website_events_id_seq to anon, authenticated;
